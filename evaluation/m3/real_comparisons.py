"""Run the 12 real disclosure comparisons and write what they show.

Usage: python evaluation/m3/real_comparisons.py  -> evaluation/m3/real_comparisons.md
Offline (saved filings in tests/fixtures/real). For each comparison: paragraph counts, what
was suppressed as noise, how many substantive changes remain, and the five largest, with the
rule-based reason and a short excerpt, plus processing time.
"""

from __future__ import annotations

import os
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
os.environ.setdefault("EM_MODE", "fixture")
os.environ.setdefault("EM_FIXTURE_DIR", str(ROOT / "tests" / "fixtures" / "real"))
os.environ.setdefault("EM_DATA_DIR", str(ROOT / "data" / "m3"))

from earnings_monitor.config import COMPANIES, load_settings  # noqa: E402
from earnings_monitor.disclosure_diff.service import SECTIONS, compare_filings  # noqa: E402
from earnings_monitor.pipeline import load_company  # noqa: E402

CASES = [("MSFT", "0000950170-25-100235"), ("MSFT", "0000950170-25-061046"),
         ("CRM", "0001108524-26-000060"), ("CRM", "0001108524-25-000088"),
         ("ADBE", "0000796343-26-000003"), ("ADBE", "0000796343-25-000073")]


def excerpt(t: str, n: int = 220) -> str:
    t = t.replace("|", "/")
    return t if len(t) <= n else t[:n].rsplit(" ", 1)[0] + " …"


def main() -> int:
    settings = load_settings()
    summary = ["| Company | Filing vs earlier | Section | Paragraphs (earlier → later) | Unchanged | Routine update | "
               "Minor edit | Split/merge | Substantive | ≥ 40 words new or dropped | Seconds |",
               "|---|---|---|---|---|---|---|---|---|---|---|"]
    detail = []
    for ticker, accn in CASES:
        data = load_company(COMPANIES[ticker], settings)[0]
        for sid in SECTIONS:
            t0 = time.perf_counter()
            comp = compare_filings(data, accn, sid, settings)
            secs = time.perf_counter() - t0
            n = comp.noise
            big = [r for r in comp.ranked if r.significance.words_added + r.significance.words_removed >= 40]
            summary.append(f"| {ticker} | {comp.new.form} {comp.new.filed} vs {comp.old.filed} | {comp.section_title} | "
                           f"{comp.diff.old_count} → {comp.diff.new_count} | {n['unchanged']} | {n['routine_update']} | "
                           f"{n['minor_edit']} | {n['split_or_merge']} | {len(comp.ranked)} | {len(big)} | {secs:.2f} |")
            detail += ["", f"### {ticker} {comp.new.form} filed {comp.new.filed} vs {comp.old.filed}: {comp.section_title}", ""]
            for r in comp.ranked[:5]:
                c = r.change
                detail.append(f"- **{c.kind}** ({r.significance.reason}) "
                              f"{'Before: ' + chr(8220) + excerpt(c.old.text) + chr(8221) + ' ' if c.old else ''}"
                              f"{'After: ' + chr(8220) + excerpt(c.new.text) + chr(8221) if c.new else ''}")
    out = ["# Disclosure comparisons on real filings", "",
           "Generated by `python evaluation/m3/real_comparisons.py` (offline). Timings exclude the first read of each "
           "filing (cached). 'Substantive' = added, removed or changed paragraphs that remain after noise suppression; "
           "whether each one actually matters is what the labeled sample measures.", ""] + summary + \
          ["", "## The five largest changes in each comparison"] + detail
    (Path(__file__).parent / "real_comparisons.md").write_text("\n".join(out) + "\n")
    print("\n".join(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
