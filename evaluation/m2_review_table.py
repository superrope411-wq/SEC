"""Write evaluation/m2/REVIEW_TABLE.md: the 19 evaluation questions with their expected answers
and source excerpts, for a person to check against the filings.

Offline, no model. For each gold quote it shows where the quote sits in the filing (evidence
ID, section, page, link) and whether retrieval offers it to the model. For questions with no
gold quote it shows the top passages retrieval would offer, so the reviewer can judge whether
an abstention is right.

  EM_MODE=fixture EM_FIXTURE_DIR=tests/fixtures/real python evaluation/m2_review_table.py
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from earnings_monitor.analysis import analyze  # noqa: E402
from earnings_monitor.config import COMPANIES, load_settings  # noqa: E402
from earnings_monitor.evidence.extract import norm  # noqa: E402
from earnings_monitor.evidence.retrieve import build_index  # noqa: E402
from earnings_monitor.explain.service import prepare  # noqa: E402
from earnings_monitor.pipeline import load_company  # noqa: E402

QUESTIONS = ROOT / "evaluation" / "m2" / "questions.csv"
OUT = ROOT / "evaluation" / "m2" / "REVIEW_TABLE.md"
COMPARISON = {"annual": "fiscal year vs prior fiscal year", "yoy": "quarter vs same quarter a year earlier",
              "sequential": "quarter vs previous quarter"}
EXPECT = {"supported": "Answer from the filing, citing the gold excerpt",
          "ambiguous": "Say the question has several readings and which one is answered",
          "unanswerable": "Insufficient evidence; no statement presented as the filing's answer",
          "inference_only": "Labeled inference (or insufficient evidence); no stated cause"}


def canon(s: str) -> str:
    return norm(s).lower().strip(" .")


def cell(s: str) -> str:
    return s.replace("|", "/").replace("\n", " ")


def main() -> int:
    settings = load_settings()
    data, _ = load_company(COMPANIES["MSFT"], settings)
    rows = list(csv.DictReader(QUESTIONS.open()))
    indexes = {}
    out = ["# Milestone 2 evaluation questions: review table", "",
           "Generated by `evaluation/m2_review_table.py` from `evaluation/m2/questions.csv` and the saved "
           "FY2025 filings. No model output appears here. Every excerpt below is copied from the filing; the "
           "link opens the filing on EDGAR at that text (the page number is the reliable locator).", "",
           "Columns: **Expected status** is what a correct final answer may end with. **Offered** says "
           "whether retrieval puts that excerpt in front of the model (measured offline).", "",
           "## Overview", "",
           "| id | split | filing | comparison | category | question | expected status | gold excerpts offered |",
           "|---|---|---|---|---|---|---|---|"]
    detail = []
    for r in rows:
        accn = r["accn"]
        if accn not in indexes:
            indexes[accn] = build_index(data, accn, settings)
        idx = indexes[accn]
        a = analyze(data, accn, r["comparison"])
        prep = prepare(r["question"], a, idx)
        offered = {h.passage.evidence_id for h in prep.hits}
        gold = [g.strip() for g in r["gold_quotes"].split("||") if g.strip()]
        found = []
        for g in gold:
            ps = [p for p in idx.passages if canon(g) in canon(p.text)]
            found.append((g, ps))
        n_off = sum(any(p.evidence_id in offered for p in ps) for _, ps in found)
        filing = f"{a.filing.form} {a.quarter.label}"
        out.append(f"| [{r['id']}](#{r['id'].lower()}) | {r['split']} | {filing} | {r['comparison']} | {r['category']} | "
                   f"{cell(r['question'])} | {r['allowed_status'].replace('|', ' or ')} | "
                   f"{f'{n_off}/{len(gold)}' if gold else 'none (no gold excerpt)'} |")

        d = [f"### {r['id']}", "",
             f"**Question:** {r['question']}", "",
             f"- Filing: {a.filing.form} {accn}, filed {a.as_of} ({a.quarter.long_label}); comparison: "
             f"{COMPARISON[r['comparison']]} ({a.current_label} vs {a.prior_label})",
             f"- Category: {r['category']}; split: {r['split']}",
             f"- Expected: {EXPECT[r['category']]}. Allowed final status: {r['allowed_status'].replace('|', ' or ')}",
             f"- Expected answer must contain: {r['required_facts'] or '-'}",
             f"- Must not: {r['must_not'] or '-'}",
             f"- Why: {r['rationale'] or '-'}"]
        if prep.gate_reason:
            d.append(f"- App behavior: stopped before any model call: {prep.gate_reason}")
        d.append("")
        if found:
            d += ["| gold excerpt (from the filing) | evidence ID | where | offered to model |", "|---|---|---|---|"]
            for g, ps in found:
                if not ps:
                    d.append(f"| {cell(g)} | not found by the extractor | - | no |")
                    continue
                p = next((x for x in ps if x.evidence_id in offered), ps[0])
                where = f"{p.section_title}, page {p.page or '?'}" + (f", under '{p.subject}'" if p.subject else "")
                d.append(f"| {cell(g)} | [`{p.evidence_id}`]({p.url}) | {cell(where)} | "
                         f"{'yes' if p.evidence_id in offered else 'no'} |")
        else:
            d.append("No gold excerpt: the filing is not expected to answer this.")
        if prep.hits and (not gold or n_off < len(gold)):
            d += ["", "Top passages retrieval would offer instead:", ""]
            for h in prep.hits[:3]:
                p = h.passage
                d.append(f"- [`{p.evidence_id}`]({p.url}) page {p.page or '?'}"
                         + (f" ({p.subject})" if p.subject else "") + f": {cell(p.text[:220])}{'…' if len(p.text) > 220 else ''}")
        d.append("")
        detail += d
    out += ["", "## Questions in detail", ""] + detail
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
